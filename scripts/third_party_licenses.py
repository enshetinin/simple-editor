#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.md from Cargo metadata.

Includes every crate linked into the shipped binaries (normal dependencies,
macOS arm64/x86_64 and Windows x86_64), with its license expression and the
license/notice files found in the crate package, plus the licenses of the
fonts embedded by egui. Identical texts are printed once.

Usage: python3 scripts/third_party_licenses.py [--check]
  --check  exit 1 if the committed file is out of date (used in CI).
"""

import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "THIRD_PARTY_LICENSES.md")
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-pc-windows-msvc"]
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense")
# Extra license files that live outside the crate root.
EXTRA_FILES = {
    "epaint_default_fonts": [
        "fonts/OFL.txt",
        "fonts/UFL.txt",
        "fonts/Hack-Regular.txt",
        "fonts/emoji-icon-font-mit-license.txt",
    ],
}


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def shipped_packages():
    packages = {}
    for target in TARGETS:
        meta = metadata(target)
        by_id = {p["id"]: p for p in meta["packages"]}
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        root = meta["resolve"]["root"]
        seen, stack = set(), [root]
        while stack:
            pid = stack.pop()
            if pid in seen:
                continue
            seen.add(pid)
            for dep in nodes[pid]["deps"]:
                if any(k["kind"] is None for k in dep["dep_kinds"]):
                    stack.append(dep["pkg"])
        for pid in seen:
            if pid != root:
                packages[pid] = by_id[pid]
    return sorted(packages.values(), key=lambda p: (p["name"], p["version"]))


TEXTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "license-texts")
PREFERENCE = ["Apache-2.0", "MIT", "BSD-3-Clause", "BSL-1.0"]


def choose_license(expr):
    """Picks one license from an SPDX expression for which we have a text."""
    for name in PREFERENCE:
        if name in expr.replace("/", " OR ").split() or name in expr:
            return name
    return None


def license_files(pkg):
    base = os.path.dirname(pkg["manifest_path"])
    files = []
    for name in sorted(os.listdir(base)):
        path = os.path.join(base, name)
        if os.path.isfile(path) and name.lower().startswith(LICENSE_PREFIXES):
            files.append(path)
    if pkg.get("license_file"):
        path = os.path.join(base, pkg["license_file"])
        if os.path.isfile(path) and path not in files:
            files.append(path)
    for rel in EXTRA_FILES.get(pkg["name"], []):
        path = os.path.join(base, rel)
        if os.path.isfile(path):
            files.append(path)
    return files


def render():
    pkgs = shipped_packages()
    texts = {}  # hash -> (text, [crate labels])
    rows = []
    missing = []
    missing_pkgs = []
    for p in pkgs:
        label = f"{p['name']} {p['version']}"
        lic = p.get("license") or "(see license file)"
        repo = p.get("repository") or ""
        rows.append(f"| {p['name']} | {p['version']} | {lic} | {repo} |")
        files = license_files(p)
        if not files:
            missing.append(label)
            missing_pkgs.append(p)
        for path in files:
            with open(path, encoding="utf-8", errors="replace") as f:
                text = f.read().strip().replace("\r\n", "\n")
            h = hashlib.sha256(text.encode()).hexdigest()
            entry = texts.setdefault(h, (text, []))
            name = os.path.relpath(path, os.path.dirname(p["manifest_path"])).replace(os.sep, "/")
            entry[1].append(f"{label} ({name})")
    lines = [
        "# Third-party licenses",
        "",
        "SimpleEditor is distributed under the MIT license (see `LICENSE`). Its",
        "binaries include the third-party software listed below. This file is",
        "generated by `scripts/third_party_licenses.py` from `Cargo.lock`; do not",
        "edit it by hand.",
        "",
        f"Crates: {len(pkgs)} (normal dependencies for {', '.join(TARGETS)}).",
        "",
        "The default egui fonts are embedded in the binary: Hack (MIT/Bitstream Vera),",
        "Ubuntu Light (Ubuntu Font Licence 1.0), Noto Emoji (SIL OFL 1.1) and",
        "emoji-icon-font (MIT). Their license texts are included below under",
        "`epaint_default_fonts`.",
        "",
        "| Crate | Version | License | Repository |",
        "|---|---|---|---|",
        *rows,
        "",
    ]
    canonical_used = []
    if missing:
        lines += [
            "## Crates without a license file in their package",
            "",
            "These crates declare their license in Cargo.toml but do not ship its",
            "text. SimpleEditor uses them under the license named below; its",
            "canonical text is reproduced in the next section. Copyright holders",
            "are the authors declared by each crate (or its repository contributors",
            "when none are declared).",
            "",
            "| Crate | Declared license | Used under | Authors (Cargo.toml) |",
            "|---|---|---|---|",
        ]
        for p in missing_pkgs:
            chosen = choose_license(p.get("license") or "")
            if chosen and chosen not in canonical_used:
                canonical_used.append(chosen)
            authors = "; ".join(p.get("authors") or []) or "see repository"
            lines.append(
                f"| {p['name']} {p['version']} | {p.get('license')} | {chosen or 'REVIEW'} | {authors} |"
            )
        lines.append("")
    lines += ["## License texts", ""]
    for name in canonical_used:
        with open(os.path.join(TEXTS, f"{name}.txt"), encoding="utf-8") as f:
            text = f.read().strip()
        lines += [f"### {name} (canonical text)", "", "```text", text, "```", ""]
    for _, (text, users) in sorted(texts.items(), key=lambda kv: kv[1][1][0]):
        lines += [f"### Used by: {', '.join(users)}", "", "```text", text, "```", ""]
    return "\n".join(lines)


def main():
    content = render()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != content:
            print("THIRD_PARTY_LICENSES.md is out of date: run scripts/third_party_licenses.py", file=sys.stderr)
            sys.exit(1)
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
